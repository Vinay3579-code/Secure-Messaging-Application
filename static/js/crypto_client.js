/**
 * CNS Cryptographic Client - ALL key material lives in the browser.
 *
 *  - Identity:  RSA-2048-PSS keypair generated here (WebCrypto); only the PUBLIC key is uploaded.
 *  - Handshake: Diffie-Hellman (RFC 3526 MODP-2048) with every public value RSA-signed and verified.
 *  - Ratchet:   the DH secret seeds two directional hash chains; every message uses a fresh key that is
 *               derived and then discarded (forward secrecy).
 *  - Cipher:    AES-256-CBC + HMAC-SHA256 (Encrypt-then-MAC) for messages and files
 *
 * Wire formats (KDF labels, signed payloads, AAD, HMAC canonical string) must stay byte-compatible with
 * crypto/ratchet.py, crypto/signatures.py, crypto/aead.py and crypto/integrity.py.
 * The server never receives a private key, shared secret, chain key, or message key.
 */

const _webcrypto = (typeof globalThis !== 'undefined' && globalThis.crypto && globalThis.crypto.subtle)
    ? globalThis.crypto
    : (typeof require === 'function' ? require('crypto').webcrypto : null);

const CNSCrypto = (() => {
    const enc = new TextEncoder();

    const P = BigInt('0x' +
        'FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD1' +
        '29024E088A67CC74020BBEA63B139B22514A08798E3404DD' +
        'EF9519B3CD3A431B302B0A6DF25F14374FE1356D6D51C245' +
        'E485B576625E7EC6F44C42E9A637ED6B0BFF5CB6F406B7ED' +
        'EE386BFB5A899FA5AE9F24117C4B1FE649286651ECE45B3D' +
        'C2007CB8A163BF0598DA48361C55D39A69163FA8FD24CF5F' +
        '83655D23DCA3AD961C62F356208552BB9ED529077096966D' +
        '670C354E4ABC9804F1746C08CA18217C32905E462E36CE3B' +
        'E39E772C180E86039B2783A2EC07A28FB5C55DF06F4C52C9' +
        'DE2BCBF6955817183995497CEA956AE515D2261898FA0510' +
        '15728E5A8AACAA68FFFFFFFFFFFFFFFF');
    const Q = (P - 1n) / 2n;   // order of the subgroup generated by g = 2
    const G = 2n;
    const MAX_SKIP = 100;
    const PSS_SALT_LEN = 222;  // max salt for RSA-2048 / SHA-256 (matches Python PSS.MAX_LENGTH)

    const INFO = {
        chainI2R: 'cns-ratchet-v2 chain initiator->responder',
        chainR2I: 'cns-ratchet-v2 chain responder->initiator',
        msgEnc: 'cns-ratchet-v2 message enc key',
        msgMac: 'cns-ratchet-v2 message mac key',
    };

    class CNSError extends Error {
        constructor(kind, message) { super(message); this.kind = kind; }  // kind: integrity | replay | protocol
    }

    // ---------- byte / hex helpers ----------
    const hexToBytes = (hex) => {
        if (hex.length % 2) hex = '0' + hex;
        const out = new Uint8Array(hex.length / 2);
        for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.substr(i * 2, 2), 16);
        return out;
    };
    const bytesToHex = (b) => Array.from(b, x => x.toString(16).padStart(2, '0')).join('');
    const bigToHex = (n) => n.toString(16);
    const normHex = (h) => BigInt('0x' + h).toString(16);
    const bigToBytes = (n, len) => hexToBytes(n.toString(16).padStart(len * 2, '0'));
    const randomBytes = (n) => _webcrypto.getRandomValues(new Uint8Array(n));

    function modPow(base, exp, mod) {
        let result = 1n;
        base %= mod;
        while (exp > 0n) {
            if (exp & 1n) result = (result * base) % mod;
            exp >>= 1n;
            base = (base * base) % mod;
        }
        return result;
    }

    // ---------- hash / MAC / KDF ----------
    const sha256 = async (data) => new Uint8Array(await _webcrypto.subtle.digest('SHA-256', data));
    const fingerprint = async (bytes) => bytesToHex(await sha256(bytes)).slice(0, 16);

    async function hmacSha256(keyBytes, dataBytes) {
        const key = await _webcrypto.subtle.importKey('raw', keyBytes, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
        return new Uint8Array(await _webcrypto.subtle.sign('HMAC', key, dataBytes));
    }

    async function hkdf(ikm, salt, info, length = 32) {
        const key = await _webcrypto.subtle.importKey('raw', ikm, 'HKDF', false, ['deriveBits']);
        const bits = await _webcrypto.subtle.deriveBits(
            { name: 'HKDF', hash: 'SHA-256', salt: salt || new Uint8Array(0), info: enc.encode(info) }, key, length * 8);
        return new Uint8Array(bits);
    }

    async function transcriptSalt(pubAHex, pubBHex) {
        return sha256(enc.encode(`${normHex(pubAHex)}:${normHex(pubBHex)}`));
    }

    async function deriveChainKeys(sharedSecret, pubAHex, pubBHex) {
        const salt = await transcriptSalt(pubAHex, pubBHex);
        return {
            initToResp: await hkdf(sharedSecret, salt, INFO.chainI2R),
            respToInit: await hkdf(sharedSecret, salt, INFO.chainR2I),
        };
    }

    async function kdfChain(chainKey) {
        return { messageKey: await hmacSha256(chainKey, new Uint8Array([1])),
                 nextChainKey: await hmacSha256(chainKey, new Uint8Array([2])) };
    }

    async function messageSubkeys(messageKey) {
        return { encKey: await hkdf(messageKey, null, INFO.msgEnc), macKey: await hkdf(messageKey, null, INFO.msgMac) };
    }

    // ---------- Diffie-Hellman ----------
    function generateDH() {
        // 256-bit private exponent (>= 2x the ~112-bit strength of a 2048-bit group), in [2, 2^256)
        let priv = 0n;
        while (priv < 2n) priv = BigInt('0x' + bytesToHex(randomBytes(32)));
        return { priv, pub: modPow(G, priv, P) };
    }
    // Range check + subgroup membership (y^q == 1): rejects small-subgroup / invalid-key attacks
    const isValidPublic = (y) => y > 1n && y < P - 1n && modPow(y, Q, P) === 1n;

    // ---------- RSA-PSS identity ----------
    const toPem = (der, label) => {
        const b64 = btoa(String.fromCharCode(...new Uint8Array(der)));
        return `-----BEGIN ${label}-----\n${b64.match(/.{1,64}/g).join('\n')}\n-----END ${label}-----\n`;
    };
    const fromPem = (pem) => {
        const b64 = pem.replace(/-----[^-]+-----/g, '').replace(/\s+/g, '');
        return Uint8Array.from(atob(b64), c => c.charCodeAt(0));
    };
    const RSA_PARAMS = { name: 'RSA-PSS', hash: 'SHA-256' };

    async function generateIdentity() {
        const kp = await _webcrypto.subtle.generateKey(
            { ...RSA_PARAMS, modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]) }, true, ['sign', 'verify']);
        return {
            priv: toPem(await _webcrypto.subtle.exportKey('pkcs8', kp.privateKey), 'PRIVATE KEY'),
            pub: toPem(await _webcrypto.subtle.exportKey('spki', kp.publicKey), 'PUBLIC KEY'),
        };
    }
    async function signText(privPem, text) {
        const key = await _webcrypto.subtle.importKey('pkcs8', fromPem(privPem), RSA_PARAMS, false, ['sign']);
        return bytesToHex(new Uint8Array(await _webcrypto.subtle.sign(
            { name: 'RSA-PSS', saltLength: PSS_SALT_LEN }, key, enc.encode(text))));
    }
    async function verifyText(pubPem, text, sigHex) {
        try {
            const key = await _webcrypto.subtle.importKey('spki', fromPem(pubPem), RSA_PARAMS, false, ['verify']);
            return await _webcrypto.subtle.verify(
                { name: 'RSA-PSS', saltLength: PSS_SALT_LEN }, key, hexToBytes(sigHex), enc.encode(text));
        } catch (e) { return false; }
    }
    const dhSignedPayload = (role, initiator, responder, pubHex) =>
        `cns-dh-v2|${role}|${initiator}|${responder}|${normHex(pubHex)}`;

    // ---------- Message ciphers ----------
    const messageContext = (sessionId, sender, receiver, messageId, mode) =>
        [sessionId, sender, receiver, messageId, mode].join('|');
    const hmacCanonical = (ivHex, ctHex, ts, seq, ctx) => enc.encode(`${ivHex}:${ctHex}:${ts}:${seq}:${ctx}`);
    const CIPHER_MODE = 'cbc-hmac';   // the only message cipher: AES-256-CBC + HMAC-SHA256 (Encrypt-then-MAC)

    async function sealMessage(mode, plaintext, encKey, macKey, ts, seq, ctx) {
        if (mode !== CIPHER_MODE) throw new CNSError('protocol', `Unsupported cipher mode '${mode}'`);
        const iv = randomBytes(16);
        const key = await _webcrypto.subtle.importKey('raw', encKey, 'AES-CBC', false, ['encrypt']);
        const ct = bytesToHex(new Uint8Array(await _webcrypto.subtle.encrypt({ name: 'AES-CBC', iv }, key, enc.encode(plaintext))));
        const tag = bytesToHex(await hmacSha256(macKey, hmacCanonical(bytesToHex(iv), ct, ts, seq, ctx)));
        return { ciphertext: ct, iv: bytesToHex(iv), tag };
    }

    async function openMessage(mode, pkt, encKey, macKey, ctx) {
        if (mode !== CIPHER_MODE) throw new CNSError('protocol', `Unsupported cipher mode '${mode}'`);
        // Encrypt-then-MAC: verify the tag (constant-time) BEFORE touching the ciphertext
        const macKeyObj = await _webcrypto.subtle.importKey('raw', macKey, { name: 'HMAC', hash: 'SHA-256' }, false, ['verify']);
        let ok = false;
        try {
            ok = await _webcrypto.subtle.verify('HMAC', macKeyObj, hexToBytes(pkt.hmac_tag),
                hmacCanonical(pkt.iv, pkt.ciphertext, pkt.timestamp, pkt.seq_no, ctx));
        } catch (e) { ok = false; }
        if (!ok) throw new CNSError('integrity', 'INTEGRITY ALERT: HMAC verification failed. Message modified, corrupted, or not for this session.');
        const key = await _webcrypto.subtle.importKey('raw', encKey, 'AES-CBC', false, ['decrypt']);
        const pt = await _webcrypto.subtle.decrypt({ name: 'AES-CBC', iv: hexToBytes(pkt.iv) }, key, hexToBytes(pkt.ciphertext));
        return new TextDecoder('utf-8', { fatal: true }).decode(pt);
    }

    // ---------- Encrypted file sharing (blob = iv(16) || AES-CBC ciphertext || HMAC-SHA256 tag(32)) ----------
    const FILE_IV = 16, FILE_TAG = 32;
    const fileAad = (fileId, sender, receiver) => enc.encode(`cns-file-v1|${fileId}|${sender}|${receiver}`);
    const sha256Hex = async (bytes) => bytesToHex(await sha256(bytes));

    // tag covers: 4-byte big-endian AAD length || AAD || iv || ciphertext
    function fileMacInput(aad, iv, ciphertext) {
        const out = new Uint8Array(4 + aad.length + iv.length + ciphertext.length);
        new DataView(out.buffer).setUint32(0, aad.length);
        out.set(aad, 4);
        out.set(iv, 4 + aad.length);
        out.set(ciphertext, 4 + aad.length + iv.length);
        return out;
    }

    async function fileSubkeys(fileKey) {
        return { encKey: await hkdf(fileKey, null, 'cns-file-v2 enc key'), macKey: await hkdf(fileKey, null, 'cns-file-v2 mac key') };
    }

    async function encryptFile(bytes, aad) {
        const fileKey = randomBytes(32);
        const { encKey, macKey } = await fileSubkeys(fileKey);
        const iv = randomBytes(FILE_IV);
        const key = await _webcrypto.subtle.importKey('raw', encKey, 'AES-CBC', false, ['encrypt']);
        const ciphertext = new Uint8Array(await _webcrypto.subtle.encrypt({ name: 'AES-CBC', iv }, key, bytes));
        const tag = await hmacSha256(macKey, fileMacInput(aad, iv, ciphertext));
        const blob = new Uint8Array(FILE_IV + ciphertext.length + FILE_TAG);
        blob.set(iv, 0);
        blob.set(ciphertext, FILE_IV);
        blob.set(tag, FILE_IV + ciphertext.length);
        return { blob, key: fileKey };
    }

    async function decryptFile(blob, fileKey, aad) {
        const fail = () => new CNSError('integrity', 'The stored file failed authentication: it was modified, corrupted, or is not for this conversation.');
        if (blob.length < FILE_IV + 16 + FILE_TAG || (blob.length - FILE_IV - FILE_TAG) % 16) throw fail();
        const iv = blob.slice(0, FILE_IV);
        const ciphertext = blob.slice(FILE_IV, blob.length - FILE_TAG);
        const tag = blob.slice(blob.length - FILE_TAG);
        const { encKey, macKey } = await fileSubkeys(fileKey);
        const macObj = await _webcrypto.subtle.importKey('raw', macKey, { name: 'HMAC', hash: 'SHA-256' }, false, ['verify']);
        // Encrypt-then-MAC: authenticate (constant time) before decrypting anything
        if (!(await _webcrypto.subtle.verify('HMAC', macObj, tag, fileMacInput(aad, iv, ciphertext)))) throw fail();
        try {
            const key = await _webcrypto.subtle.importKey('raw', encKey, 'AES-CBC', false, ['decrypt']);
            return new Uint8Array(await _webcrypto.subtle.decrypt({ name: 'AES-CBC', iv }, key, ciphertext));
        } catch (e) { throw fail(); }
    }

    return { P, Q, G, MAX_SKIP, CNSError, fileAad, sha256Hex, encryptFile, decryptFile, hexToBytes, bytesToHex, bigToHex, normHex, bigToBytes, randomBytes, modPow,
             sha256, fingerprint, hmacSha256, hkdf, deriveChainKeys, kdfChain, messageSubkeys, generateDH, isValidPublic,
             generateIdentity, signText, verifyText, dhSignedPayload, messageContext, sealMessage, openMessage };
})();

const CNSError = CNSCrypto.CNSError;

class SecureCryptoClient {
    constructor(username) {
        if (!_webcrypto) throw new Error('WebCrypto is unavailable. Open the app via http://localhost:5000 or https:// (a secure context).');
        this.username = username;
        this.identityPrivateKey = null; // RSA private key PEM (stays in this browser)
        this.identityPublicKey = null;  // RSA public key PEM

        this.cipherMode = 'cbc-hmac';   // fixed: AES-256-CBC + HMAC-SHA256
        this.plainLog = new Map();      // message_id -> plaintext (keys are erased, so this is the only way to re-show history)
        this._lock = Promise.resolve();
        this.resetSession();
        this.loadIdentity();
    }

    getHeaders() {
        return { 'Content-Type': 'application/json', 'X-Sim-User': this.username };
    }

    resetSession() {
        this.peer = null;
        this.sessionId = null;
        this.isInitiator = false;
        this.p_hex = null;
        this.g = 2;
        this.privateDH = null;          // BigInt, never leaves memory
        this.publicDH_hex = null;
        this.peerPublicDH_hex = null;
        this.isSessionEstablished = false;
        this.peerSigVerified = false;   // set once the peer's RSA-PSS signature on their DH value checked out

        this.sharedSecretFingerprint = null;
        this.sendCK = null; this.recvCK = null;
        this.sendN = 0; this.recvN = 0;
        this.sendCKFp = null; this.recvCKFp = null;
        this.lastMessageKeyFp = null;
        this.skipped = new Map();       // seq_no -> message key (out-of-order tolerance)
        this.ratchetLog = [];
        this.plainLog = new Map();
    }

    // ---------------- identity ----------------
    loadIdentity() {
        try {
            const priv = localStorage.getItem(`cns_identity_priv_${this.username}`);
            const pub = localStorage.getItem(`cns_identity_pub_${this.username}`);
            if (priv && pub) { this.identityPrivateKey = priv; this.identityPublicKey = pub; }
        } catch (e) { /* storage unavailable */ }
    }

    /**
     * Makes sure this browser holds an RSA identity key matching the one published on the server.
     * Generates and publishes a new keypair (re-authenticating with the password) if not.
     */
    static async ensureIdentity(username, password, serverPublicKey) {
        let priv = null, pub = null;
        try {
            priv = localStorage.getItem(`cns_identity_priv_${username}`);
            pub = localStorage.getItem(`cns_identity_pub_${username}`);
        } catch (e) {}
        const same = (a, b) => a && b && a.replace(/\s+/g, '') === b.replace(/\s+/g, '');
        if (priv && pub && same(pub, serverPublicKey)) return false;

        const kp = await CNSCrypto.generateIdentity();
        const resp = await fetch('/api/auth/identity', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ username, password, public_identity_key: kp.pub })
        });
        const data = await resp.json();
        if (!data.success) throw new Error(data.error || 'Could not publish identity key');
        localStorage.setItem(`cns_identity_priv_${username}`, kp.priv);
        localStorage.setItem(`cns_identity_pub_${username}`, kp.pub);
        return true;
    }

    _withLock(fn) {
        const run = this._lock.then(fn, fn);
        this._lock = run.catch(() => {});
        return run;
    }

    _requireIdentity() {
        if (!this.identityPrivateKey) {
            throw new Error('No identity key in this browser. Log out and log in again on /login to create one.');
        }
    }

    async getPeerIdentityKey(peer) {
        const resp = await fetch('/api/auth/users', { headers: this.getHeaders() });
        const data = await resp.json();
        const u = (data.users || []).find(x => x.username === peer);
        if (!u || !u.public_identity_key) throw new Error(`${peer} has not published an identity key yet (they must log in once).`);
        return u.public_identity_key;
    }

    // ---------------- handshake ----------------
    _checkGroup(p_hex, g) {
        if (BigInt('0x' + p_hex) !== CNSCrypto.P || BigInt(g) !== CNSCrypto.G) {
            throw new CNSError('protocol', 'PROTOCOL ALERT: peer proposed a non-standard DH group. Handshake aborted.');
        }
    }

    /** Step 1: Alice generates A, signs it with her RSA identity key, publishes both. */
    async initiateDH(peerUsername, onStepUpdate) {
        this._requireIdentity();
        this.resetSession();
        this.peer = peerUsername;
        this.isInitiator = true;
        const say = onStepUpdate || (() => {});

        say('1. Generating 2048-bit DH keypair in this browser (private a never leaves memory)...');
        const kp = CNSCrypto.generateDH();
        this.privateDH = kp.priv;
        this.publicDH_hex = CNSCrypto.bigToHex(kp.pub);
        this.p_hex = CNSCrypto.bigToHex(CNSCrypto.P);
        this.g = 2;

        say('2. Signing public value A with RSA-2048-PSS (binds A to my identity and this peer)...');
        const sig = await CNSCrypto.signText(this.identityPrivateKey,
            CNSCrypto.dhSignedPayload('A', this.username, peerUsername, this.publicDH_hex));

        const resp = await fetch('/api/dh/initiate', {
            method: 'POST',
            headers: this.getHeaders(),
            body: JSON.stringify({ peer: peerUsername, p_hex: this.p_hex, g: this.g, pub_a: this.publicDH_hex, sig_a: sig })
        });
        const result = await resp.json();
        if (!result.success) throw new Error(result.error || 'DH Initiate Failed');

        this.sessionId = result.session_id;
        say(`3. Published signed A to relay (Session ${this.sessionId}). Waiting for ${peerUsername}...`);
        return this.sessionId;
    }

    /** Step 2: Bob verifies Alice's signature, then answers with a signed B. */
    async respondDH(sess, onStepUpdate) {
        this._requireIdentity();
        this.resetSession();
        const say = onStepUpdate || (() => {});
        this.sessionId = sess.session_id;
        this.peer = sess.user1;
        this.isInitiator = false;

        say(`1. Received DH invitation from ${this.peer}. Verifying their RSA signature on A (anti-MITM)...`);
        this._checkGroup(sess.dh_p, sess.dh_g);
        this.p_hex = sess.dh_p; this.g = sess.dh_g;
        this.peerPublicDH_hex = sess.pub_a;
        const peerKey = await this.getPeerIdentityKey(this.peer);
        const okSig = await CNSCrypto.verifyText(peerKey,
            CNSCrypto.dhSignedPayload('A', sess.user1, sess.user2, sess.pub_a), sess.sig_a || '');
        if (!okSig) throw new CNSError('protocol', `MITM ALERT: signature on ${this.peer}'s public value A is INVALID. Handshake aborted.`);
        const peerPub = BigInt('0x' + sess.pub_a);
        if (!CNSCrypto.isValidPublic(peerPub)) throw new CNSError('protocol', 'PROTOCOL ALERT: peer DH value fails subgroup validation.');
        this.peerSigVerified = true;
        say('   Signature valid ✓ and public value passes subgroup check ✓');

        say('2. Generating my keypair (b, B), signing B, computing S = A^b mod p...');
        const kp = CNSCrypto.generateDH();
        this.privateDH = kp.priv;
        this.publicDH_hex = CNSCrypto.bigToHex(kp.pub);
        const sigB = await CNSCrypto.signText(this.identityPrivateKey,
            CNSCrypto.dhSignedPayload('B', sess.user1, this.username, this.publicDH_hex));
        await this._startRatchet(peerPub, sess.pub_a, this.publicDH_hex);

        say('3. Publishing signed B to relay...');
        const resp = await fetch('/api/dh/respond', {
            method: 'POST',
            headers: this.getHeaders(),
            body: JSON.stringify({ session_id: this.sessionId, pub_b: this.publicDH_hex, sig_b: sigB })
        });
        const result = await resp.json();
        if (!result.success) throw new Error(result.error || 'DH Respond Failed');

        this.isSessionEstablished = true;
        say('4. Secure channel ready: hash ratchet initialised, every message gets a fresh one-time key.');
        return true;
    }

    /** Step 3: Alice verifies Bob's signature on B and finishes. */
    async finalizeDH(sess, onStepUpdate) {
        const say = onStepUpdate || (() => {});
        say(`4. Received ${this.peer}'s public value B. Verifying RSA signature...`);
        const peerKey = await this.getPeerIdentityKey(this.peer);
        const okSig = await CNSCrypto.verifyText(peerKey,
            CNSCrypto.dhSignedPayload('B', sess.user1, sess.user2, sess.pub_b), sess.sig_b || '');
        if (!okSig) throw new CNSError('protocol', `MITM ALERT: signature on ${this.peer}'s public value B is INVALID. Handshake aborted.`);
        const peerPub = BigInt('0x' + sess.pub_b);
        if (!CNSCrypto.isValidPublic(peerPub)) throw new CNSError('protocol', 'PROTOCOL ALERT: peer DH value fails subgroup validation.');

        this.peerSigVerified = true;
        this.peerPublicDH_hex = sess.pub_b;
        await this._startRatchet(peerPub, this.publicDH_hex, sess.pub_b);
        this.isSessionEstablished = true;
        say('5. Signature valid ✓. Secure channel ready: hash ratchet initialised.');
        return true;
    }

    /** S = peer^priv mod p  ->  directional chain keys (HKDF, bound to the handshake transcript). */
    async _startRatchet(peerPub, pubAHex, pubBHex) {
        const S = CNSCrypto.bigToBytes(CNSCrypto.modPow(peerPub, this.privateDH, CNSCrypto.P), 256);
        await this.initRatchet(S, pubAHex, pubBHex, this.isInitiator);
        this.privateDH = null; // no longer needed: forward secrecy of the handshake
    }

    async initRatchet(sharedSecret, pubAHex, pubBHex, isInitiator) {
        const { initToResp, respToInit } = await CNSCrypto.deriveChainKeys(sharedSecret, pubAHex, pubBHex);
        this.sendCK = isInitiator ? initToResp : respToInit;
        this.recvCK = isInitiator ? respToInit : initToResp;
        this.sendN = 0; this.recvN = 0;
        this.skipped = new Map();
        this.sharedSecretFingerprint = await CNSCrypto.fingerprint(sharedSecret);
        this.sendCKFp = await CNSCrypto.fingerprint(this.sendCK);
        this.recvCKFp = await CNSCrypto.fingerprint(this.recvCK);
        this.ratchetLog = [];
        sharedSecret.fill(0);
    }

    /** Structured event for the Crypto Inspector: {dir, n, ckBefore, mk, ckAfter, note}. */
    _logRatchet(entry) {
        this.ratchetLog.push({ time: Date.now(), ...entry });
        if (this.ratchetLog.length > 24) this.ratchetLog.shift();
    }

    // ---------------- messaging ----------------
    _context(sender, receiver, messageId, mode) {
        return CNSCrypto.messageContext(this.sessionId, sender, receiver, messageId, mode);
    }

    /** Ratchet the sending chain, encrypt with the one-time key, then forget that key. */
    encryptMessage(plaintext) {
        return this._withLock(async () => {
            if (!this.isSessionEstablished) throw new Error("No active secure session. Click 'Start Handshake (DH)' first.");
            const mode = this.cipherMode;

            const oldFp = this.sendCKFp;
            const { messageKey, nextChainKey } = await CNSCrypto.kdfChain(this.sendCK);
            this.sendCK.fill(0);               // the old chain key is destroyed: past keys cannot be re-derived
            this.sendCK = nextChainKey;
            const seq = ++this.sendN;
            this.sendCKFp = await CNSCrypto.fingerprint(nextChainKey);
            this.lastMessageKeyFp = await CNSCrypto.fingerprint(messageKey);
            this._logRatchet({ dir: 'send', n: seq, ckBefore: oldFp, mk: this.lastMessageKeyFp, ckAfter: this.sendCKFp });

            const { encKey, macKey } = await CNSCrypto.messageSubkeys(messageKey);
            messageKey.fill(0);

            const timestamp = new Date().toISOString();
            const messageId = `msg-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
            const ctx = this._context(this.username, this.peer, messageId, mode);
            const sealed = await CNSCrypto.sealMessage(mode, plaintext, encKey, macKey, timestamp, seq, ctx);
            encKey.fill(0); macKey.fill(0);

            this.plainLog.set(messageId, plaintext);
            return {
                message_id: messageId, receiver: this.peer, sender: this.username,
                ciphertext: sealed.ciphertext, iv: sealed.iv, hmac_tag: sealed.tag,
                timestamp, seq_no: seq, cipher_mode: mode
            };
        });
    }

    /**
     * Advance the receiving chain to this packet, authenticate, decrypt. Ratchet state is committed only if
     * authentication succeeds, so forged packets cannot burn keys or desynchronise the chain.
     */
    verifyAndDecrypt(pkt) {
        return this._withLock(async () => {
            if (!this.isSessionEstablished || !this.recvCK) {
                throw new CNSError('protocol', 'Session not yet synchronized. Please complete the Diffie-Hellman handshake.');
            }
            const mode = pkt.cipher_mode || 'cbc-hmac';
            if (mode !== 'cbc-hmac') throw new CNSError('protocol', `Unsupported cipher mode '${mode}'. Only CBC + HMAC-SHA256 is accepted.`);
            const ctx = this._context(pkt.sender, pkt.receiver || this.username, pkt.message_id, mode);
            const n = Number(pkt.seq_no);
            const open = async (mk) => {
                const { encKey, macKey } = await CNSCrypto.messageSubkeys(mk);
                return CNSCrypto.openMessage(mode, pkt, encKey, macKey, ctx);
            };

            let plaintext;
            if (this.skipped.has(n)) {
                const mk = this.skipped.get(n);
                plaintext = await open(mk);
                mk.fill(0);
                this.skipped.delete(n);
                this._logRatchet({ dir: 'recv', n, mk: null, note: 'out-of-order: stored key used, then deleted' });
            } else if (n <= this.recvN) {
                throw new CNSError('replay', `REPLAY ALERT: message #${n} was already consumed (receive chain is at #${this.recvN}). Its key no longer exists.`);
            } else if (n - this.recvN > CNSCrypto.MAX_SKIP) {
                throw new CNSError('protocol', `Message #${n} is too far ahead of chain position #${this.recvN}.`);
            } else {
                let ck = this.recvCK, target = null;
                const newlySkipped = new Map();
                for (let i = this.recvN + 1; i <= n; i++) {
                    const step = await CNSCrypto.kdfChain(ck);
                    if (i === n) target = step.messageKey; else newlySkipped.set(i, step.messageKey);
                    ck = step.nextChainKey;
                }
                plaintext = await open(target);                       // throws on forgery -> nothing below runs
                const oldFp = this.recvCKFp;
                this.recvCK.fill(0);
                this.recvCK = ck; this.recvN = n;
                this.recvCKFp = await CNSCrypto.fingerprint(ck);
                this.lastMessageKeyFp = await CNSCrypto.fingerprint(target);
                target.fill(0);
                for (const [i, k] of newlySkipped) this.skipped.set(i, k);
                while (this.skipped.size > CNSCrypto.MAX_SKIP) this.skipped.delete(Math.min(...this.skipped.keys()));
                this._logRatchet({ dir: 'recv', n, ckBefore: oldFp, mk: this.lastMessageKeyFp, ckAfter: this.recvCKFp,
                                   note: newlySkipped.size ? `${newlySkipped.size} skipped key(s) stored` : '' });
            }
            this.plainLog.set(pkt.message_id, plaintext);
            return plaintext;
        });
    }
}

